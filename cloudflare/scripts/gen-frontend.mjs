// Turns ../frontend/index.html into src/frontend.generated.ts (a string export) with the API
// endpoint set to the same-origin "/api". Replaces the Workers Assets upload, which Terraform
// cannot do without a separate upload step, so the page is bundled into the Worker instead.
import { readFileSync, writeFileSync } from "node:fs";

const html = readFileSync(new URL("../../frontend/index.html", import.meta.url), "utf8");
if (!html.includes("__GET_UPLOAD_URL_ENDPOINT__")) throw new Error("endpoint placeholder not found in frontend/index.html");
const rendered = html.replaceAll("__GET_UPLOAD_URL_ENDPOINT__", "/api");
writeFileSync(
  new URL("../src/frontend.generated.ts", import.meta.url),
  `// GENERATED by scripts/gen-frontend.mjs from frontend/index.html. Do not edit.\nexport default ${JSON.stringify(rendered)};\n`,
);
console.log("wrote src/frontend.generated.ts");
